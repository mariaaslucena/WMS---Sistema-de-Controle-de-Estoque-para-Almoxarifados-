-- Modelo físico / DDL do MVP
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS remessas; DROP TABLE IF EXISTS movimentacoes; DROP TABLE IF EXISTS estoque; DROP TABLE IF EXISTS posicoes; DROP TABLE IF EXISTS escolas; DROP TABLE IF EXISTS produtos; DROP TABLE IF EXISTS categorias; DROP TABLE IF EXISTS usuarios;
CREATE TABLE usuarios (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,nome VARCHAR(120) NOT NULL,login VARCHAR(80) NOT NULL UNIQUE,senha_hash VARCHAR(255) NOT NULL,perfil ENUM('OPERADOR','GESTOR') NOT NULL DEFAULT 'OPERADOR',ativo TINYINT(1) NOT NULL DEFAULT 1,criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE categorias (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,nome VARCHAR(100) NOT NULL UNIQUE,ativo TINYINT(1) NOT NULL DEFAULT 1,criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE produtos (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,categoria_id INT UNSIGNED NULL,nome VARCHAR(160) NOT NULL,descricao VARCHAR(255) NULL,unidade_medida VARCHAR(30) NOT NULL DEFAULT 'UN',estoque_minimo DECIMAL(12,3) NOT NULL DEFAULT 0,ativo TINYINT(1) NOT NULL DEFAULT 1,criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,CONSTRAINT fk_produto_categoria FOREIGN KEY (categoria_id) REFERENCES categorias(id) ON UPDATE CASCADE ON DELETE SET NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE escolas (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,nome VARCHAR(180) NOT NULL,codigo VARCHAR(50) NULL UNIQUE,ativo TINYINT(1) NOT NULL DEFAULT 1,criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE posicoes (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,rua CHAR(1) NOT NULL,numero TINYINT UNSIGNED NOT NULL,ativo TINYINT(1) NOT NULL DEFAULT 1,criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,CONSTRAINT uq_posicao UNIQUE (rua,numero),CONSTRAINT chk_rua CHECK (rua IN ('A','B','C','D','E','F','G')),CONSTRAINT chk_numero CHECK (numero BETWEEN 1 AND 40)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE estoque (id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,produto_id INT UNSIGNED NOT NULL,posicao_id INT UNSIGNED NOT NULL,quantidade DECIMAL(12,3) NOT NULL DEFAULT 0,atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,CONSTRAINT uq_estoque_produto_posicao UNIQUE (produto_id,posicao_id),CONSTRAINT fk_estoque_produto FOREIGN KEY (produto_id) REFERENCES produtos(id) ON UPDATE CASCADE ON DELETE RESTRICT,CONSTRAINT fk_estoque_posicao FOREIGN KEY (posicao_id) REFERENCES posicoes(id) ON UPDATE CASCADE ON DELETE RESTRICT,CONSTRAINT chk_estoque_quantidade CHECK (quantidade >= 0)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE movimentacoes (id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,tipo ENUM('ENTRADA','SAIDA') NOT NULL,produto_id INT UNSIGNED NOT NULL,posicao_id INT UNSIGNED NOT NULL,escola_id INT UNSIGNED NULL,usuario_id INT UNSIGNED NOT NULL,quantidade DECIMAL(12,3) NOT NULL,observacao VARCHAR(500) NULL,criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,CONSTRAINT fk_mov_produto FOREIGN KEY (produto_id) REFERENCES produtos(id) ON UPDATE CASCADE ON DELETE RESTRICT,CONSTRAINT fk_mov_posicao FOREIGN KEY (posicao_id) REFERENCES posicoes(id) ON UPDATE CASCADE ON DELETE RESTRICT,CONSTRAINT fk_mov_escola FOREIGN KEY (escola_id) REFERENCES escolas(id) ON UPDATE CASCADE ON DELETE RESTRICT,CONSTRAINT fk_mov_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON UPDATE CASCADE ON DELETE RESTRICT,CONSTRAINT chk_mov_quantidade CHECK (quantidade > 0)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE remessas (id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,movimentacao_id BIGINT UNSIGNED NOT NULL UNIQUE,numero_guia VARCHAR(60) NOT NULL UNIQUE,arquivo_pdf VARCHAR(255) NULL,criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,CONSTRAINT fk_remessa_mov FOREIGN KEY (movimentacao_id) REFERENCES movimentacoes(id) ON UPDATE CASCADE ON DELETE RESTRICT) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
